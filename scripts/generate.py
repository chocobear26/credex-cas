#!/usr/bin/env python3
"""Regenerate every file that restates something written elsewhere.

The instructions are written once:

    AGENTS.md                     the always-on contract — who Jarvis is, the rules, the checklist
    .claude/rules/*.md            the conventions for one artifact type, scoped with `paths:`
    .claude/skills/*/SKILL.md     an operation — the change-request protocol
    schema.yml                    the artifact types

and stamped into the files that need to restate them:

    .github/instructions/*.instructions.md   Copilot's dialect of each rule (`paths:` -> `applyTo:`)
    .github/prompts/*.prompt.md              a door that lets `/change-request` be typed in Copilot
    AGENTS.md                                the artifact type table, from schema.yml
    index.html                               the instructions shown on the landing page

and the history is written once — versions in content/change_log/changeLog.md, assessments as
content/sources/okf_assessment_*.md — and restated as

    content/log.md                           the Open Knowledge Format log (§9): one list entry per
                                             version and per assessment, grouped under its date,
                                             newest first

Why the Copilot copies exist at all: VS Code reads `AGENTS.md` at the workspace root and discovers
skills in `.claude/skills/` directly, so the contract and the protocol need no copy. But the
`.claude/rules` location Copilot supports is user-profile only, so a project's scoped rules must be
restated under `.github/instructions/`; and Copilot matches a skill on its description rather than
on a name you type, so the prompt file is what makes the operation typable. Each prompt names its
skill and stops, so the protocol still exists in exactly one place.

Usage:
    python3 scripts/generate.py            # write
    python3 scripts/generate.py --check    # exit 1 if anything is stale (make build)
"""

from __future__ import annotations

import html
import re
import sys
from pathlib import Path

import yaml

from okflib import latest_human_approval, okf_datetime, trust_tier

ROOT = Path(__file__).resolve().parent.parent
AGENTS = ROOT / "AGENTS.md"
RULES = ROOT / ".claude" / "rules"
SKILLS = ROOT / ".claude" / "skills"
COPILOT = ROOT / ".github"
LANDING = ROOT / "index.html"
SCHEMA = ROOT / "schema.yml"
CHANGE_LOG = ROOT / "content" / "change_log" / "changeLog.md"
SOURCES = ROOT / "content" / "sources"
LOG = ROOT / "content" / "log.md"
CONTENT = ROOT / "content"
TRACE = CONTENT / "traceability" / "rueckverfolgung.md"
APPROVALS = CONTENT / "traceability" / "freigaben.md"
ASSESSMENT_RE = re.compile(r"okf_assessment_(\d{4})_(\d{2})_(\d{2})(?:_(\d+))?\.md")
VERSION_RE = re.compile(r"^## (v\d+\.\d+) – (.+?) \((\d{4}-\d{2}-\d{2})\)\s*\n+(.+?)\n", re.M)

FRONTMATTER_RE = re.compile(r"\A---\n(.*?)\n---\n?", re.DOTALL)
NOTE = "<!-- GENERATED by scripts/generate.py — do not edit. Edit {source} and run `make generate`. -->"


def split(text: str) -> tuple[dict, str]:
    match = FRONTMATTER_RE.match(text)
    if not match:
        return {}, text
    return yaml.safe_load(match.group(1)) or {}, text[match.end():]


def copilot_files() -> dict[Path, str]:
    out = {}
    for src in sorted(RULES.glob("*.md")):
        meta, body = split(src.read_text(encoding="utf-8"))
        globs = meta.get("paths") or []
        apply_to = ",".join(globs if isinstance(globs, list) else [globs])
        rel = src.relative_to(ROOT).as_posix()
        out[COPILOT / "instructions" / f"{src.stem}.instructions.md"] = (
            f'---\napplyTo: "{apply_to}"\n---\n\n{NOTE.format(source=rel)}\n\n{body.lstrip()}'
        )
    for src in sorted(SKILLS.glob("*/SKILL.md")):
        meta, _ = split(src.read_text(encoding="utf-8"))
        name, rel = src.parent.name, src.relative_to(ROOT).as_posix()
        out[COPILOT / "prompts" / f"{name}.prompt.md"] = (
            f"---\nagent: agent\ndescription: {meta['description']}\n---\n\n"
            f"{NOTE.format(source=rel)}\n\n"
            f"Run the **{name}** operation.\n\n"
            f"Read `{rel}` and follow it exactly, together with `AGENTS.md`. This file is only the\n"
            "door; the skill is the procedure. Anything the user typed after the command is the input.\n"
        )
    return out


def types_table() -> str:
    types = (yaml.safe_load(SCHEMA.read_text(encoding="utf-8")) or {})["types"]
    rows = ["| Type | Where | Rules | Holds |", "|---|---|---|---|"]
    for name, spec in types.items():
        rules = f"`.claude/rules/{spec['rules']}`" if spec.get("rules") else "—"
        rows.append(f"| `{name}` | `content/{spec['where']}` | {rules} | {spec['holds']} |")
    return "\n".join(rows)


def replace_block(text: str, name: str, body: str) -> str:
    pattern = re.compile(rf"(<!--\s*{name}:start[^>]*-->\n).*?(<!--\s*{name}:end\s*-->)", re.DOTALL)
    if not pattern.search(text):
        raise SystemExit(f"generate: no <!-- {name}:start --> block in the target file")
    return pattern.sub(lambda m: m.group(1) + body + "\n" + m.group(2), text)


def landing_page(current: str, agents: str) -> str:
    """The landing page shows the instructions Jarvis runs on, embedded as static Markdown."""
    sources = [("AGENTS.md", agents)]
    sources += [(p.relative_to(ROOT).as_posix(), p.read_text(encoding="utf-8")) for p in sorted(SKILLS.glob("*/SKILL.md"))]
    sources += [(p.relative_to(ROOT).as_posix(), p.read_text(encoding="utf-8")) for p in sorted(RULES.glob("*.md"))]
    parts = []
    for rel, text in sources:
        _, body = split(text)
        body = re.sub(r"<!--.*?-->\n?", "", body, flags=re.DOTALL)  # generated-block markers
        parts.append(f"<p class=\"file-badge\">{html.escape(rel)}</p>\n\n{body.strip()}\n")
    markdown = "\n\n---\n\n".join(parts)
    if "</script" in markdown.lower():
        raise SystemExit("generate: an instruction file contains </script>, which would end the embed early")
    new = re.sub(r'(<script id="raw-md" type="text/markdown">\n).*?(\n  </script>)',
                 lambda m: m.group(1) + markdown + m.group(2), current, count=1, flags=re.DOTALL)
    new = re.sub(r'<div class="file-badge">[^<]*</div>',
                 '<div class="file-badge">AGENTS.md · .claude/skills · .claude/rules</div>', new, count=1)
    return new


def assessment_entries(sources: Path) -> dict[str, list[str]]:
    """One log entry per filed assessment, keyed by the day it ran, the day's later runs first."""
    runs = []
    for path in sources.glob("okf_assessment_*.md"):
        match = ASSESSMENT_RE.fullmatch(path.name)
        if not match:
            raise SystemExit(f"generate: {path.name} is not named okf_assessment_<yyyy>_<mm>_<dd>[_<n>].md")
        meta, _ = split(path.read_text(encoding="utf-8"))
        if not meta.get("title") or not meta.get("description"):
            raise SystemExit(f"generate: {path.name} needs a title and a description for its log entry")
        yyyy, mm, dd, run = match.groups()
        runs.append((f"{yyyy}-{mm}-{dd}", int(run or 1),
                     f"- **Assessment:** [{meta['title']}](sources/{path.name}) — {str(meta['description']).strip()}"))
    groups: dict[str, list[str]] = {}
    for day, _, entry in sorted(runs, key=lambda r: (r[0], r[1]), reverse=True):
        groups.setdefault(day, []).append(entry)
    return groups


def okf_log(change_log: Path = CHANGE_LOG, sources: Path = SOURCES) -> str:
    """content/log.md — the versions and the assessments as the date-grouped list OKF v0.2 §9 specifies.

    Within a day, assessments come first: an assessment checks the documentation as released, so it is
    the newer entry.
    """
    versions = VERSION_RE.findall(change_log.read_text(encoding="utf-8"))
    if not versions:
        raise SystemExit("generate: no `## vX.Y – Title (YYYY-MM-DD)` sections found in the change log")
    groups = assessment_entries(sources)
    for version, title, day, summary in versions:
        groups.setdefault(day, []).append(
            # The summary's own links are relative to the change log's folder, so only their text travels.
            f"- **Release:** [{version} – {title}](change_log/changeLog.md) — {re.sub(r'\[([^\]]+)\]\([^)]+\)', r'\1', summary.strip())}")
    out = ["---", 'title: "Log"', "type: log",
           'description: "Jede Version der Dokumentation und jedes Konformitäts-Assessment, neueste zuerst."',
           "weight: 80", "---", "",
           NOTE.format(source="content/change_log/changeLog.md or file an assessment in content/sources/"),
           "", "# Log", ""]
    for day in sorted(groups, reverse=True):
        out += [f"## {day}", "", *groups[day], ""]
    return "\n".join(out)


def _rows(text: str, prefix: str) -> list[list[str]]:
    """Table rows of a catalog whose first cell starts with `prefix` (GA, FA-, NFA-)."""
    out = []
    for line in text.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if line.startswith("|") and cells and re.fullmatch(rf"{prefix}\d+", cells[0]):
            out.append(cells)
    return out


def traceability(content: Path = CONTENT) -> str:
    """content/traceability/rueckverfolgung.md — from the stories and the requirement catalogs.

    Every user story names its business requirements (`· GA: GA1, GA3`) and its requirements
    (`- Anforderungen: [FA-03](…)`); its use case comes from `sources:`. The page lists the chain
    GA → story → FA/NFA → use case and every element nothing traces to.
    """
    req = content / "requirements"
    ga = _rows((req / "geschaeftsanforderungen.md").read_text(encoding="utf-8"), "GA")
    fa = _rows((req / "funktionaleAnforderungen.md").read_text(encoding="utf-8"), "FA-")
    nfa = _rows((req / "nichtfunktionaleAnforderungen.md").read_text(encoding="utf-8"), "NFA-")
    ucs = {}
    for path in sorted((content / "use_case").glob("*/*.md"), key=lambda p: p.read_text(encoding="utf-8").split("title:", 1)[1][:40]):
        meta, body = split(path.read_text(encoding="utf-8"))
        if meta.get("type") != "use-case":
            continue
        uc_id = re.search(r"UC-\d+", meta.get("title", "")).group(0)
        quality = body.split("## Qualitätsanforderungen", 1)[-1].split("---", 1)[0] if "## Qualitätsanforderungen" in body else ""
        ucs[path.relative_to(content).as_posix()] = (uc_id, meta.get("linkTitle", uc_id), sorted(set(re.findall(r"N?FA-\d+", quality)), key=lambda r: (r.startswith("N"), int(r.split("-")[1]))))
    stories = []
    for path in sorted((content / "epics" / "user_stories").glob("us_*.md"), key=lambda p: [int(x) for x in re.findall(r"\d+", p.stem)]):
        meta, body = split(path.read_text(encoding="utf-8"))
        sid, title = meta["title"].split(" – ", 1)
        tags = meta.get("tags", [])
        uc = next((ucs[s["resource"].lstrip("/")] for s in meta.get("sources", []) if s["resource"].lstrip("/") in ucs), ("–", "–", []))
        ga_m = re.search(r"· GA: ([^\n]+)", body)
        req_m = re.search(r"^- Anforderungen: ([^\n]+)$", body, re.M)
        stories.append({
            "id": sid, "title": title, "file": path.name, "uc": uc,
            "ga": re.findall(r"GA\d+", ga_m.group(1)) if ga_m else [],
            "req": re.findall(r"N?FA-\d+", req_m.group(1)) if req_m else [],
            "release": next((t.upper().split("-")[0] for t in tags if re.fullmatch(r"r\d-.*", t)), "–"),
            "moscow": next((t.capitalize() for t in tags if t in ("must", "should", "could")), "–"),
            "kano": next(({"basic": "Basis", "performance": "Leistung", "attractive": "Begeisterung"}[t.split("-")[1]] for t in tags if t.startswith("kano-")), "–"),
            "criteria": body.count("**Gegeben**"),
        })
    us_link = lambda s: f"[{s['id']}](../epics/user_stories/{s['file']})"
    fa_link = lambda r: f"[{r}](../requirements/{'nichtfunktionaleAnforderungen' if r.startswith('NFA') else 'funktionaleAnforderungen'}.md)"
    lines = ["---", 'title: "Rückverfolgung – CredEx Phase 1"', 'linkTitle: "Rückverfolgungsmatrix"', "type: traceability-matrix",
             'description: "Von jeder Geschäftsanforderung über die User Stories zu den funktionalen und nicht-funktionalen Anforderungen und Use Cases, mit allem, worauf nichts verweist."',
             "weight: 1", "---", "", NOTE.format(source="the user stories and content/requirements/"), "",
             "# Rückverfolgung – CredEx Phase 1", "",
             "Diese Seite wird von `make generate` aus den User Stories und den Anforderungskatalogen erzeugt. Sie zeigt, dass jede Geschäftsanforderung bis zu Use Case und Abnahmekriterium durchgezogen ist, und listet alles, worauf nichts verweist.", "",
             "---", "", "## Von der Geschäftsanforderung zur Umsetzung", "",
             "| GA | Geschäftsanforderung | User Stories | FA / NFA | Use Cases |", "|---|---|---|---|---|"]
    for g in ga:
        st = [s for s in stories if g[0] in s["ga"]]
        reqs = sorted({r for s in st for r in s["req"]}, key=lambda r: (r.startswith("N"), int(r.split("-")[1])))
        uc_ids = sorted({s["uc"][0] for s in st})
        lines.append(f"| **{g[0]}** | {g[1]} | {', '.join(us_link(s) for s in st) or '–'} | {', '.join(fa_link(r) for r in reqs) or '–'} | {', '.join(uc_ids) or '–'} |")
    lines += ["", "---", "", "## User Stories", "",
              "| Story | Titel | Release | MoSCoW | KANO | Use Case | GA | FA / NFA | Abnahmekriterien |", "|---|---|---|---|---|---|---|---|---|"]
    for s in stories:
        lines.append(f"| {us_link(s)} | {s['title']} | {s['release']} | {s['moscow']} | {s['kano']} | {s['uc'][1]} | {', '.join(s['ga']) or '–'} | {', '.join(fa_link(r) for r in s['req']) or '–'} | {s['criteria']} |")
    lines += ["", "---", "", "## Use Cases und Qualitätsanforderungen", "",
              "| Use Case | User Stories | Qualitätsanforderungen |", "|---|---|---|"]
    for rel, (uc_id, label, quality) in ucs.items():
        st = [s for s in stories if s["uc"][0] == uc_id]
        lines.append(f"| [{label}](../{rel}) | {', '.join(us_link(s) for s in st) or '–'} | {', '.join(fa_link(r) for r in quality) or '–'} |")
    referenced = {r for s in stories for r in s["req"]} | {r for _, _, q in ucs.values() for r in q}
    gaps = []
    gaps += [f"- **{g[0]}** {g[1]}: keine User Story" for g in ga if not any(g[0] in s["ga"] for s in stories)]
    gaps += [f"- **{r[0]}** {r[1]}: keine User Story und kein Use Case" for r in fa + nfa if r[0] not in referenced]
    gaps += [f"- **{uc_id}**: keine User Story" for uc_id, _, _ in ucs.values() if not any(s["uc"][0] == uc_id for s in stories)]
    gaps += [f"- **{s['id']}**: keine Geschäftsanforderung" for s in stories if not s["ga"]]
    lines += ["", "---", "", "## Lücken", "",
              "Anforderungen, die nur auf Systemebene gelten (Betrieb, Sicherheit), haben oft keine eigene Story; sie werden mit ihrem Abnahmekriterium direkt geprüft.", ""]
    lines += gaps or ["Keine."]
    return "\n".join(lines) + "\n"


def approvals(content: Path = CONTENT) -> str:
    """content/traceability/freigaben.md — which artifact a person has approved, and which not yet."""
    skip = {"section", "log", "traceability-matrix", "approval-status"}
    rows, done, outdated_n = [], 0, 0
    for path in sorted(content.rglob("*.md")):
        meta, _ = split(path.read_text(encoding="utf-8"))
        if meta.get("type") in skip:
            continue
        events = meta.get("verified") or []
        events = events if isinstance(events, list) else [events]
        who = sorted({str(e.get("by", "")).removeprefix("human:") for e in events
                      if isinstance(e, dict) and str(e.get("by", "")).startswith("human:")})
        tier = trust_tier(meta)
        done += tier == "human-reviewed"
        gen_at = okf_datetime((meta.get("generated") or {}).get("at"))
        approved = latest_human_approval(meta)
        outdated = bool(approved and gen_at and gen_at > approved)
        outdated_n += outdated
        rel = path.relative_to(content).as_posix()
        state = {"unverified": "○ Entwurf", "machine-confirmed": "◐ maschinell bestätigt",
                 "human-reviewed": "✔ freigegeben"}[tier] + (" · **seither geändert**" if outdated else "")
        rows.append(f"| [{meta.get('title', rel)}](../{rel}) | `{meta.get('type', '')}` | "
                    f"{gen_at.strftime('%Y-%m-%d') if gen_at else '–'} | {state} | "
                    f"{', '.join(who) + ' (' + approved.strftime('%Y-%m-%d') + ')' if who and approved else '**offen**'} |")
    total = len(rows)
    lines = ["---", 'title: "Freigaben – CredEx Phase 1"', 'linkTitle: "Freigaben"', "type: approval-status",
             f'description: "Welche Artefakte ein Mensch aus der Gruppe geprüft und freigegeben hat: {done} von {total}."',
             "weight: 2", "---", "", NOTE.format(source="the `verified:` keys (recorded with make verify)"), "",
             "# Freigaben – CredEx Phase 1", "",
             f"**{done} von {total} Artefakten freigegeben.** Jarvis schreibt Entwürfe (`generated`); freigegeben ist ein Artefakt erst, wenn ein Mensch aus der Gruppe es gelesen hat und das mit `make verify PAGES=\"…\" WHO=<name>` festhält – oder ohne Installation über GitHub: *Actions → Freigabe erfassen → Run workflow*.", "",
             "Die **Vertrauensstufe** leitet sich aus `verified` ab, wie es das Open Knowledge Format vorsieht: ○ *Entwurf* ohne Freigabe, ◐ *maschinell bestätigt*, wenn nur ein Prozess bestätigt hat, ✔ *freigegeben*, sobald ein Mensch freigegeben hat. *Seither geändert* heisst, dass Jarvis das Artefakt nach der letzten Freigabe neu geschrieben hat; dann gilt die Freigabe nur für die frühere Fassung. Jede Seite zeigt ihre Stufe auch oben im Text.", "",
             f"**Seither geändert:** {outdated_n}.", "",
             "| Artefakt | Typ | Zuletzt geschrieben | Vertrauensstufe | Freigegeben von |", "|---|---|---|---|---|", *rows]
    return "\n".join(lines) + "\n"


def main() -> int:
    check = "--check" in sys.argv[1:]
    wanted = copilot_files()
    agents = replace_block(AGENTS.read_text(encoding="utf-8"), "schema-types", types_table())
    wanted[AGENTS] = agents
    wanted[LANDING] = landing_page(LANDING.read_text(encoding="utf-8"), agents)
    wanted[LOG] = okf_log()
    wanted[TRACE] = traceability()
    wanted[APPROVALS] = approvals()

    stale = []
    for existing in sorted((COPILOT / "instructions").glob("*.md")) + sorted((COPILOT / "prompts").glob("*.md")):
        if existing not in wanted:
            stale.append(f"{existing.relative_to(ROOT)} (no source any more)")
            if not check:
                existing.unlink()
    for path, text in wanted.items():
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        stale.append(str(path.relative_to(ROOT)))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")

    if check and stale:
        print(f"generate: STALE — run `make generate` ({', '.join(stale)})", file=sys.stderr)
        return 1
    print(f"generate: {'updated ' + ', '.join(stale) if stale else 'up to date'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
